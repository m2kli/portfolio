#!/usr/bin/env python3
"""Assemble the portfolio copy of the Level Workbench into public/demos/level-workbench/.

The workbench lives in its own repo; GitHub Actions can't see it, so the output is
committed here. Re-run after changing the workbench or the maps:

    python scripts/build_workbench.py
    python scripts/build_workbench.py --workbench D:/path/LevelWorkbench --jinci D:/path/JinciLevelTest
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

import sys

sys.stdout.reconfigure(encoding='utf-8')
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public' / 'demos' / 'level-workbench'

# Runtime files copied verbatim from the workbench repo.
RUNTIME = ['workbench.css', 'viewer-pacing.js', 'map-validate.js', 'map-geometry.js',
           'workbench-3d.js', 'workbench.js', 'vendor/three.min.js', 'AI_GUIDE.html', 'AI_MAP_SPEC.html']


def maps_for(workbench: Path, jinci: Path) -> list[tuple[str, Path]]:
    """The maps shown on the portfolio, in list order."""
    return [
        ('ai-sample', workbench / 'AI_MAP_SAMPLE.json'),
        ('sample-multifloor', workbench / 'maps' / 'sample-multifloor.json'),
        ('egypt', workbench / 'maps' / 'egypt.json'),
        ('china', workbench / 'maps' / 'china.json'),
        ('jinci', jinci / 'maps' / 'jinci-full.json'),
    ]


def compact(value):
    # same as LevelWorkbench/tools/build.py
    if isinstance(value, dict):
        return {k: compact(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [compact(v) for v in value]
    return value


def build(workbench: Path, jinci: Path) -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for rel in RUNTIME:
        dest = OUT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(workbench / rel, dest)

    maps = {}
    for key, path in maps_for(workbench, jinci):
        data = compact(json.loads(path.read_text(encoding='utf-8-sig')))
        maps[key] = data
        print(f"{key:18} {data.get('meta', {}).get('title', '')}  rooms={len(data.get('rooms', []))} enemies={len(data.get('enemies', []))}")
    (OUT / 'maps.js').write_text(
        '/* Generated by portfolio/scripts/build_workbench.py; do not edit. */\n'
        'window.WORKBENCH_MAPS=' + json.dumps(maps, ensure_ascii=False, separators=(',', ':')) + ';\n',
        encoding='utf-8')

    # index.html: same page, plus a link back to the portfolio and a note that this is the showcase build.
    html = (workbench / 'index.html').read_text(encoding='utf-8')
    back = ('<a class="wb-link" href="../../works/level-workbench/" target="_top" '
            'title="返回作品集 / Back to portfolio">← 作品集</a>\n      ')
    html, n = re.subn(r'(<a class="wb-link" href="AI_GUIDE\.html")', back + r'\1', html, count=1)
    if n != 1:
        raise SystemExit('index.html: could not find the AI_GUIDE link to anchor the back link')
    # The source page still carries its original project's branding.
    rebrand = [
        (r'<title>[^<]*</title>', '<title>关卡设计工作台 · 作品集演示</title>'),
        (r'<span class="wb-mark">[^<]*</span>', '<span class="wb-mark">L</span>'),
        (r'(<div><b>关卡工作台</b><span>)[^<]*(</span>)', r'\1LEVEL DESIGN WORKBENCH · PORTFOLIO DEMO\2'),
        (r'(<p class="wb-hint">)[^<]*(</p>)', r'\1作品集演示版：5 张示例地图。也可以导入任何符合规范的地图 JSON，不需要改代码。\2'),
        (r"(font-weight='600' fill='white' text-anchor='middle'%3E)9(%3C)", r'\1L\2'),
    ]
    for pattern, repl in rebrand:
        html, n = re.subn(pattern, repl, html, count=1)
        if n != 1:
            raise SystemExit(f'index.html: pattern not found: {pattern}')
    (OUT / 'index.html').write_text(html, encoding='utf-8')

    size = sum(f.stat().st_size for f in OUT.rglob('*') if f.is_file())
    print(f'wrote {OUT.relative_to(ROOT)} ({size / 1024:.0f} KB)')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--workbench', type=Path, default=Path('C:/Users/m2k/Documents/LevelWorkbench'))
    ap.add_argument('--jinci', type=Path, default=Path('C:/Users/m2k/Documents/JinciLevelTest'))
    args = ap.parse_args()
    build(args.workbench, args.jinci)
